def render_text(text: str, color: str = "primary") -> Text:
    """Render text in block-letter ASCII art.

    Args:
        text: The text to render.
        color: Color name from COLORS dict.

    Returns:
        Rich Text object with the rendered banner.
    """
    lines = [""] * 7
    for char in text.upper():
        if char in FONT_5x7:
            char_lines = FONT_5x7[char]
        else:
            char_lines = ["     ", "     ", "     ", "     ", "     ", "     ", "     "]
        for i in range(7):
            lines[i] += char_lines[i] + " "

    result = Text()
    for line in lines:
        result.append(line.rstrip() + "\n", style=Style(color=COLORS[color], bold=True))

    return result